def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def _safe_file(path, limit=MAX_BINARY):
    path = Path(path).absolute()
    parent = overlay._directory(path.parent)
    descriptor = None
    try:
        descriptor = os.open(path.name, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=parent)
        before = os.fstat(descriptor)
        if not stat.S_ISREG(before.st_mode) or before.st_size > limit:
            raise ValueError('invalid_package_input')
        with os.fdopen(descriptor, 'rb') as source:
            descriptor = None
            raw = source.read(limit + 1)
            after = os.fstat(source.fileno())
        identity = lambda value: (value.st_dev, value.st_ino, value.st_size, value.st_mtime_ns, value.st_ctime_ns)
        if identity(before) != identity(after) or len(raw) != before.st_size:
            raise ValueError('package_input_changed')
        return raw
    except OSError as error:
        raise ValueError('invalid_package_input') from error
    finally:
        if descriptor is not None:
            os.close(descriptor)
        os.close(parent)


def _zip_members(archive, *, limit=1024 * 1024 * 1024):
    infos = archive.infolist()
    if len(infos) > 30000 or len({item.filename for item in infos}) != len(infos):
        raise ValueError('duplicate_or_excessive_zip_entry')
    result = {}
    total = 0
    for item in infos:
        name = item.filename
        overlay._name(name[:-1] if item.is_dir() else name)
        kind = stat.S_IFMT(item.external_attr >> 16)
        if (kind not in (0, stat.S_IFREG, stat.S_IFDIR) or item.flag_bits & 1
                or (kind == stat.S_IFDIR and not item.is_dir())):
            raise ValueError('unsafe_zip_member')
        total += item.file_size
        if item.file_size > MAX_BINARY or total > limit:
            raise ValueError('zip_content_limit')
        if not item.is_dir():
            result[name] = item
    return result


def inspect_macho(raw):
    """Arm64 iOS identity and signing-independent section bytes, no disassembly."""
    if len(raw) < 32:
        raise ValueError('macho_header')
    magic, cpu, subtype, kind, count, size, flags, reserved = struct.unpack_from('<8I', raw)
    if (magic != 0xfeedfacf or cpu != 0x100000c or subtype & 0xffffff != 0
            or kind not in (2, 6, 8) or not 1 <= count <= 4096 or size > len(raw) - 32):
        raise ValueError('macho_arm64_identity')
    cursor, end = 32, 32 + size
    identity, platform = None, None
    sections, loads = {}, []
    # codesign may add/replace LC_CODE_SIGNATURE using existing header padding.
    # Bind every other header field and LC byte, with only __LINKEDIT's two
    # signature-growth sizes normalized; entry points/rpaths/imports stay exact.
    execution_metadata = [struct.pack('<6I', magic, cpu, subtype, kind, flags, reserved)]
    normalization_ranges = [(16, 24)]  # ncmds/sizeofcmds can grow by signature LC.
    signature_offset = None
    signed = False
    for _ in range(count):
        if cursor + 8 > end:
            raise ValueError('macho_load_commands')
        command, length = struct.unpack_from('<II', raw, cursor)
        if length < 8 or length % 4 or cursor + length > end:
            raise ValueError('macho_load_commands')
        if command == 0x1b:
            if length != 24 or identity is not None:
                raise ValueError('macho_uuid')
            identity = raw[cursor + 8:cursor + 24].hex()
        elif command == 0x32:
            if length < 24 or platform is not None:
                raise ValueError('macho_platform')
            platform = struct.unpack_from('<I', raw, cursor + 8)[0]
        elif command in (0x21, 0x2c):
            if length < 20 or struct.unpack_from('<I', raw, cursor + 16)[0] != 0:
                raise ValueError('encrypted_binary_not_unsigned_source_build')
        elif command in (0xc, 0x80000018, 0x8000001f, 0x20):
            offset = struct.unpack_from('<I', raw, cursor + 8)[0]
            if not 24 <= offset < length:
                raise ValueError('macho_dylib_command')
            loads.append(raw[cursor + offset:cursor + length].split(b'\0', 1)[0].decode('utf-8'))
        elif command == 0x19:
            if length < 72:
                raise ValueError('macho_sections')
            section_count = struct.unpack_from('<I', raw, cursor + 64)[0]
            if section_count > 4096 or length != 72 + 80 * section_count:
                raise ValueError('macho_sections')
            for index in range(section_count):
                at = cursor + 72 + 80 * index
                section = raw[at:at + 16].split(b'\0', 1)[0].decode('ascii')
                segment = raw[at + 16:at + 32].split(b'\0', 1)[0].decode('ascii')
                size = struct.unpack_from('<Q', raw, at + 40)[0]
                offset = struct.unpack_from('<I', raw, at + 48)[0]
                section_flags = struct.unpack_from('<I', raw, at + 64)[0]
                key = segment + '/' + section
                if key in sections:
                    raise ValueError('macho_duplicate_section')
                if section_flags & 0xff in (1, 0xc, 0x12):
                    sections[key] = {'bytes': size, 'zero_fill': True}
                else:
                    if offset + size > len(raw) or (size and offset < end):
                        raise ValueError('macho_section_bounds')
                    sections[key] = {'bytes': size, 'offset': offset, 'sha256': sha(raw[offset:offset + size])}
        elif command == 0x1d:
            if length != 16:
                raise ValueError('macho_code_signature')
            offset, size = struct.unpack_from('<II', raw, cursor + 8)
            if signature_offset is not None or offset < end or offset + size != len(raw) or size < 12:
                raise ValueError('macho_code_signature')
            signature_offset = offset
            normalization_ranges.append((cursor, cursor + length))
            signature = raw[offset:offset + size]
            signature_magic, signature_size, entries = struct.unpack_from('>III', signature)
            if signature_magic != 0xfade0cc0 or signature_size > size or entries > 128 or 12 + entries * 8 > signature_size:
                raise ValueError('macho_code_signature')
            directories = 0
            for index in range(entries):
                slot, at = struct.unpack_from('>II', signature, 12 + index * 8)
                if at + 8 > signature_size:
                    raise ValueError('macho_code_signature')
                blob_magic, blob_size = struct.unpack_from('>II', signature, at)
                if blob_size < 8 or at + blob_size > signature_size:
                    raise ValueError('macho_code_signature')
                if slot == 0x10000 and blob_size > 8:
                    raise ValueError('developer_signature_not_allowed')
                if blob_magic == 0xfade0c02:
                    if blob_size < 44:
                        raise ValueError('macho_code_directory')
                    version, signing_flags = struct.unpack_from('>II', signature, at + 8)
                    if not signing_flags & 2:
                        raise ValueError('developer_signature_not_allowed')
                    if version >= 0x20200 and (blob_size < 52 or struct.unpack_from('>I', signature, at + 48)[0]):
                        raise ValueError('team_identifier_not_allowed')
                    directories += 1
            if not directories:
                raise ValueError('macho_code_directory')
            signed = True
        if command != 0x1d:
            normalized = bytearray(raw[cursor:cursor + length])
            if command == 0x19 and raw[cursor + 8:cursor + 24].split(b'\0', 1)[0] == b'__LINKEDIT':
                if length != 72:
                    raise ValueError('macho_linkedit_layout')
                normalized[32:40] = b'\0' * 8  # vmsize
                normalized[48:56] = b'\0' * 8  # filesize
                normalization_ranges.extend(((cursor + 32, cursor + 40), (cursor + 48, cursor + 56)))
            execution_metadata.append(bytes(normalized))
        cursor += length
    if cursor != end or platform != 2 or identity is None or not sections:
        raise ValueError('macho_ios_identity')
    # Include section-external bind/symbol/fixup bytes too. Only a terminal
    # signature blob and the closed header/LC ranges above are mutable.
    content = bytearray(raw[:signature_offset] if signature_offset is not None else raw)
    for start, stop in normalization_ranges:
        content[start:stop] = b'\0' * (stop - start)
    return {'uuid': identity, 'arch': 'arm64', 'platform': 'ios', 'kind': kind,
            'sections': sections, 'dylibs': loads, 'adhoc_signed': signed, 'sha256': sha(raw),
            'execution_metadata_sha256': sha(b''.join(execution_metadata)),
            'code_content_bytes': len(content), 'code_content_sha256': sha(content),
            'code_content_padded16_sha256': sha(content + b'\0' * (-len(content) % 16))}


def inspect_probe_ipa(path, *, build_number, source_sha256, stamp, products):
    if (type(build_number) is not str or re.fullmatch(r'[1-9][0-9]{5,9}', build_number) is None
            or not 800000 <= int(build_number) <= 2147483647 or not overlay._sha(source_sha256)):
        raise ValueError('probe_build_identity')
    products = overlay._root(products)
    original_ipa_sha256 = sha(_safe_file(path, 1024 * 1024 * 1024))
    base = 'Payload/LoopCtrlAllInOne.app/'
    plugin = base + 'PlugIns/LoopCtrlUITests.xctest/'
    images = {}
    with zipfile.ZipFile(path) as archive:
        members = _zip_members(archive)
        if archive.testzip() is not None:
            raise ValueError('ipa_crc_failure')
        if any(name.lower().endswith(('.mobileprovision', '.p12', '.pfx', '.pem', '.key')) for name in members):
            raise ValueError('private_signing_material_not_allowed')
        def required(name):
            if name not in members or not members[name].file_size:
                raise ValueError('missing_package_member')
            return archive.read(name)
        for directory, executable, kind in ((base, 'LoopCtrlAllInOne', 2), (plugin, 'LoopCtrlUITests', 8)):
            info_raw = required(directory + 'Info.plist')
            info = plistlib.loads(info_raw)
            expected_identity = {'CFBundleIdentifier': 'top.ebato.loopctrl', 'CFBundleExecutable': executable,
                'CFBundleVersion': build_number, **BUILD_MARKERS, 'NG8CaptureProbeSourceSHA256': source_sha256}
            if type(info) is not dict or any(info.get(key) != value for key, value in expected_identity.items()):
                types = {str: 'string', bool: 'boolean', int: 'integer', float: 'real', list: 'array',
                         dict: 'dictionary', bytes: 'data', datetime: 'date', type(None): 'null', plistlib.UID: 'uid'}
                fields = {}
                for key, expected in expected_identity.items():
                    present = type(info) is dict and key in info
                    observed = info[key] if present else None
                    fields[key] = {'present': present, 'type': types.get(type(observed), 'unsupported') if present else 'missing',
                                   'match': present and observed == expected}
                error = ValueError('probe_plist_identity')
                error._ng8_identity_diagnostic = {'schema': 'ng8-package-diagnostic-v1', 'code': 'probe_plist_identity',
                    'bundle_role': 'app' if directory == base else 'test', 'fields': fields}
                raise error
            local_info = _safe_file(products / (directory + 'Info.plist').removeprefix('Payload/'), 1024 * 1024)
            if plistlib.loads(local_info) != info:
                raise ValueError('compiled_product_plist_mismatch')
            name = directory + executable
            raw = required(name)
            image = inspect_macho(raw)
            if image['kind'] != kind:
                raise ValueError('probe_executable_kind')
            names = [name]
            debug = executable + '.debug.dylib'
            if any(item in ('@rpath/' + debug, '@executable_path/' + debug) for item in image['dylibs']):
                names.append(directory + debug)
            found_stamp = False
            for code_name in names:
                code = required(code_name)
                observed = inspect_macho(code)
                built = inspect_macho(_safe_file(products / code_name.removeprefix('Payload/')))
                content_match = (observed['code_content_bytes'] == built['code_content_bytes']
                    and observed['code_content_sha256'] == built['code_content_sha256'])
                # A newly added signature may align an unsigned EOF upward by
                # at most 15 zero bytes. Never permit truncation or arbitrary
                # content changes between two already-signed images.
                content_match |= (observed['adhoc_signed'] and not built['adhoc_signed']
                    and observed['code_content_bytes'] == (built['code_content_bytes'] + 15) // 16 * 16
                    and observed['code_content_sha256'] == built['code_content_padded16_sha256'])
                if (observed['uuid'], observed['kind'], observed['sections'], observed['execution_metadata_sha256']) != (
                        built['uuid'], built['kind'], built['sections'], built['execution_metadata_sha256']) or not content_match:
                    raise ValueError('ipa_compiled_product_mismatch')
                found_stamp |= any(stamp.encode('ascii') in code[row['offset']:row['offset'] + row['bytes']]
                    for row in observed['sections'].values() if not row.get('zero_fill'))
                images[code_name] = observed
            if not found_stamp:
                raise ValueError('compiled_build_stamp_missing')
        required(plugin + 'loopctrl')
        # Any other Mach-O image must also be unsigned/ad-hoc, including dylibs.
        for name, info in members.items():
            if name in images or info.file_size < 4:
                continue
            with archive.open(info) as source:
                magic = source.read(4)
            if magic == b'\xcf\xfa\xed\xfe':
                inspect_macho(archive.read(info))
            elif magic in (b'\xca\xfe\xba\xbe', b'\xbe\xba\xfe\xca', b'\xca\xfe\xba\xbf'):
                raise ValueError('unexpected_fat_binary')
    report = legacy.inspect_ipa(path)
    if report['ipa_sha256'] != original_ipa_sha256:
        raise ValueError('package_input_changed')
    return dict(report, probe_build_markers={**BUILD_MARKERS, 'NG8CaptureProbeSourceSHA256': source_sha256},
                compiled_build_stamp=stamp, code_images=images, ipa_bytes=Path(path).stat().st_size)


def generated_stamp(raw):
    try:
        text = raw.decode('utf-8')
    except UnicodeError as error:
        raise ValueError('generated_stamp_format') from error
    matched = re.fullmatch(re.escape(STAMP_TEMPLATE).replace('%s', r'([0-9]{4}-[0-9]{2}-[0-9]{2} [0-9]{2}:[0-9]{2})'), text)
    if matched is None:
        raise ValueError('generated_stamp_format')
    try:
        datetime.strptime(matched[1], '%Y-%m-%d %H:%M')
    except ValueError as error:
        raise ValueError('generated_stamp_datetime') from error
    return matched[1]


def _git(root, *args):
    result = subprocess.run(['git', '-C', str(root), *args], capture_output=True, timeout=60)
    if result.returncode:
        raise ValueError('source_git_provenance')
    return result.stdout


def git_inventory(root, revision):
    """Hash the complete committed Git tree, including the one known link blob."""
    if re.fullmatch('[0-9a-f]{40}', revision) is None:
        raise ValueError('source_commit_identity')
    records = []
    for row in _git(root, 'ls-tree', '-rz', revision).split(b'\0'):
        if not row:
            continue
        try:
            metadata, encoded_name = row.split(b'\t', 1)
            mode, kind, oid = metadata.decode('ascii').split()
            name = overlay._name(encoded_name.decode('utf-8'))
        except (UnicodeError, ValueError) as error:
            raise ValueError('source_git_inventory') from error
        if kind != 'blob' or mode not in ('100644', '100755', '120000') or (mode == '120000' and name != LINK_PATH):
            raise ValueError('source_git_inventory_type')
        records.append((name, mode, oid))
    if not records or len(records) > 30000 or len({row[0] for row in records}) != len(records):
        raise ValueError('source_git_inventory')
    # One batch avoids one subprocess per source file. Bounded public Git blobs
    # are data, never shell commands, and no Git configuration/credential is read.
    query = ''.join(oid + '\n' for _, _, oid in records).encode('ascii')
    result = subprocess.run(['git', '-C', str(root), 'cat-file', '--batch'], input=query,
                            capture_output=True, timeout=60)
    if result.returncode or len(result.stdout) > 1024 * 1024 * 1024:
        raise ValueError('source_git_blobs')
    data, cursor, inventory = result.stdout, 0, {}
    for name, mode, oid in records:
        end = data.find(b'\n', cursor)
        try:
            actual_oid, kind, size = data[cursor:end].decode('ascii').split()
            size = int(size)
        except (UnicodeError, ValueError) as error:
            raise ValueError('source_git_blobs') from error
        cursor = end + 1
        if actual_oid != oid or kind != 'blob' or not 0 <= size <= MAX_BINARY or cursor + size >= len(data):
            raise ValueError('source_git_blobs')
        raw = data[cursor:cursor + size]
        cursor += size
        if data[cursor:cursor + 1] != b'\n':
            raise ValueError('source_git_blobs')
        cursor += 1
        inventory[name] = {'sha256': sha(raw), 'bytes': size, 'mode': mode}
    if cursor != len(data):
        raise ValueError('source_git_blobs')
    return inventory


def _fixed_link(root):
    parent = overlay._directory((root / LINK_PATH).parent)
    try:
        leaf = Path(LINK_PATH).name
        before = os.stat(leaf, dir_fd=parent, follow_symlinks=False)
        target = os.readlink(leaf, dir_fd=parent)
        after = os.stat(leaf, dir_fd=parent, follow_symlinks=False)
        if not stat.S_ISLNK(before.st_mode) or before != after or target != LINK_TARGET:
            raise ValueError('fixed_source_link_mismatch')
    finally:
        os.close(parent)


def verify_tree(root, expected):
    """Private synthetic seam; production obtains expected only from Git/seals."""
    observed = {}
    for name, row in expected.items():
        overlay._name(name)
        if row['mode'] == '120000':
            if name != LINK_PATH or row['sha256'] != sha(LINK_TARGET.encode()):
                raise ValueError('fixed_source_link_mismatch')
            _fixed_link(root)
            raw = _safe_file(root / 'Scripts/loopctrl_rpc.py')
        else:
            raw = _safe_file(root / name)
            if sha(raw) != row['sha256']:
                raise ValueError('complete_source_hash_mismatch')
        observed[name] = sha(raw)
    return observed


def inspect_sources(upstream, driver):
    upstream, driver = overlay._root(upstream), overlay._root(driver)
    if driver != HERE.parents[2]:
        raise ValueError('driver_verifier_location_mismatch')
    if _git(driver, 'status', '--porcelain=v1', '-z', '--untracked-files=all'):
        raise ValueError('driver_checkout_not_clean')
    driver_commit = _git(driver, 'rev-parse', 'HEAD').decode().strip()
    driver_files = verify_tree(driver, git_inventory(driver, driver_commit))
    baseline = overlay._trusted_baseline(upstream)
    manifest_raw = overlay._read_path(HERE / 'manifest.json')
    manifest = overlay._validate(overlay._json(manifest_raw), baseline)
    patch = overlay._read_path(HERE / 'overlay.patch')
    if sha(patch) != manifest['patch_sha256']:
        raise ValueError('overlay_patch_hash_mismatch')
    overlay._patch_headers(patch, manifest['files'])
    overlay._assets(HERE / 'assets', manifest['additions'])
    effective = overlay.effective_expected_map(manifest, baseline)
    expected = git_inventory(upstream, UPSTREAM)
    for name, digest in effective.items():
        expected[name] = {'sha256': digest, 'mode': expected.get(name, {}).get('mode', '100644')}
    if expected[STAMP_SCRIPT]['sha256'] != STAMP_SCRIPT_SHA256 or sha(_safe_file(upstream / STAMP_SCRIPT)) != STAMP_SCRIPT_SHA256:
        raise ValueError('stamp_generator_changed')
    stamp_raw = _safe_file(upstream / STAMP, 4096)
    stamp = generated_stamp(stamp_raw)
    expected[STAMP] = {'sha256': sha(stamp_raw), 'mode': '100644'}
    # Only the literal generator output gets an extra tracked-delta permission.
    # Every old/new sealed path is still verified against the actual final tree.
    overlay._checkout_delta(upstream, (*manifest['files'], STAMP), manifest['additions'])
    overlay._new_inventory(upstream, manifest['additions'])
    final = verify_tree(upstream, expected)
    project = 'LoopCtrl.xcodeproj/project.pbxproj'
    final[project] = sha(_safe_file(upstream / project, 16 * 1024 * 1024))
    legacy.require_runtime_response_api(_safe_file(upstream / 'LoopCtrlUITests/NG2Runtime.swift').decode(), '1.98.16-ngg2')
    complete = {'driver/' + name: digest for name, digest in driver_files.items()}
    complete.update({'upstream/' + name: digest for name, digest in final.items()})
    return {'upstream_commit': UPSTREAM, 'driver_commit': driver_commit,
        'baseline_sha256': dict(overlay.BASELINE_PINS), 'overlay_manifest_sha256': sha(manifest_raw),
        'overlay_patch_sha256': sha(patch), 'final_source_sha256': final,
        'complete_source_sha256': complete, 'complete_source_materialized_links': dict(MATERIALIZED_LINKS),
        'build_stamp': {'path': STAMP, 'value': stamp, 'sha256': sha(stamp_raw),
                        'generator_sha256': STAMP_SCRIPT_SHA256}, 'manifest': manifest}


def inspect_source_zip(path, complete):
    with zipfile.ZipFile(path) as archive:
        members = _zip_members(archive)
        if set(members) != set(complete):
            raise ValueError('complete_source_zip_inventory')
        for name, digest in complete.items():
            if not (name.startswith('driver/') or name.startswith('upstream/')) or sha(archive.read(members[name])) != digest:
                raise ValueError('complete_source_zip_hash')
    raw = _safe_file(path, 1024 * 1024 * 1024)
    return {'sha256': sha(raw), 'bytes': len(raw), 'files': len(complete), 'verified': True}


def _relative(upstream, supplied):
    path = Path(supplied)
    if not path.is_absolute():
        path = upstream / path
    try:
        name = path.relative_to(upstream).as_posix()
    except ValueError as error:
        raise ValueError('compiler_source_outside_checkout') from error
    overlay._name(name)
    return name


def _defines(arguments):
    found = set()
    for index, value in enumerate(arguments):
        if value == '-D':
            if index + 1 >= len(arguments):
                raise ValueError('compiler_define_missing_value')
            found.add(arguments[index + 1])
        elif value.startswith('-D'):
            found.add(value[2:])
    return found


def _option(arguments, name):
    if arguments.count(name) != 1:
        raise ValueError('compiler_option_missing_or_duplicate')
    index = arguments.index(name)
    if index + 1 >= len(arguments):
        raise ValueError('compiler_option_missing_value')
    return arguments[index + 1]


def swift_sources(upstream, arguments):
    names, lists = set(), []
    for index, token in enumerate(arguments):
        if token.endswith('.swift'):
            names.add(_relative(upstream, token))
        elif token == '-filelist':
            if index + 1 >= len(arguments):
                raise ValueError('swift_filelist_missing_value')
            name = _relative(upstream, arguments[index + 1])
            if not name.startswith('build/'):
                raise ValueError('swift_filelist_outside_build')
            raw = _safe_file(upstream / name, 2 * 1024 * 1024)
            try:
                entries = shlex.split(raw.decode('utf-8'))
            except (UnicodeError, ValueError) as error:
                raise ValueError('swift_filelist_encoding') from error
            if not entries or len(entries) > 20000 or any(not entry.endswith('.swift') for entry in entries):
                raise ValueError('swift_filelist_inventory')
            names.update(_relative(upstream, entry) for entry in entries)
            lists.append({'path': name, 'sha256': sha(raw), 'bytes': len(raw)})
    return names, lists


def inspect_swift_records(upstream, records, source_report):
    """Private fixture seam for actual, already-expanded compiler argv records."""
    upstream = Path(upstream)
    manifest = source_report['manifest']
    final = source_report['final_source_sha256']
    swift_additions = {name for name in manifest['additions'] if name.endswith('.swift')}
    per_target, filelists, compiled_sources = {}, [], {}
    for row in records:
        module, arguments = row.get('module'), row.get('arguments')
        if module not in TARGETS:
            continue
        if not isinstance(arguments, list) or not arguments or Path(arguments[0]).name != 'swiftc':
            raise ValueError('probe_swift_arguments')
        if '-c' not in arguments and '-emit-object' not in arguments:
            continue
        defines = _defines(arguments)
        triple = _option(arguments, '-target')
        if ('NG8_CAPTURE_PROBE_BUILD' not in defines or not triple.startswith('arm64-apple-ios')
                or '-simulator' in triple or '-macabi' in triple
                or (module == 'LoopCtrlAllInOne' and 'LOOPCTRL_ALL_IN_ONE' not in defines)):
            raise ValueError('probe_swift_target_or_flags')
        names, used_lists = swift_sources(upstream, arguments)
        required = {STAMP, 'LoopCtrlKit/NG8CaptureMode.swift'}
        if module == 'LoopCtrlUITests':
            required |= swift_additions
            if _relative(upstream, _option(arguments, '-import-objc-header')) != 'LoopCtrlUITests/XCTestPrivate-Bridging-Header.h':
                raise ValueError('probe_swift_bridge_header')
        elif names & (swift_additions - {'LoopCtrlKit/NG8CaptureMode.swift'}):
            raise ValueError('uitest_source_in_app_target')
        if not required <= names:
            raise ValueError('probe_swift_membership')
        for name in names:
            raw = _safe_file(upstream / name, 8 * 1024 * 1024)
            digest = sha(raw)
            if name not in final:
                generated = ('build/Build/Intermediates.noindex/LoopCtrl.build/Debug-iphoneos/'
                             + module + '.build/DerivedSources/GeneratedAssetSymbols.swift')
                if name != generated:
                    raise ValueError('unsealed_compiled_swift_source')
                final[name] = digest
                source_report['complete_source_sha256']['upstream/' + name] = digest
            if final[name] != digest:
                raise ValueError('compiled_swift_source_changed')
            compiled_sources[name] = digest
        filelists.extend(used_lists)
        per_target.setdefault(module, []).append({'defines': sorted(defines), 'target_triple': triple,
            'source_sha256': {name: compiled_sources[name] for name in sorted(names)},
            'command_sha256': row['command_sha256']})
    if set(per_target) != TARGETS:
        raise ValueError('probe_swift_target_evidence_missing')
    return {'targets': per_target, 'filelists': filelists, 'compiled_source_sha256': compiled_sources}


def inspect_compiler(upstream, build_log, profile_directory, source_report):
    upstream = overlay._root(upstream)
    log = _safe_file(build_log, compiler.MAX_BUILD_LOG_BYTES)
    profile = compiler.read_compile_profile(upstream, required_version=3)
    saved = overlay._json(_safe_file(Path(profile_directory) / 'perception-compile-profile.json', 4 * 1024 * 1024))
    if profile != saved or profile['build_log_sha256'] != sha(log):
        raise ValueError('actual_compile_profile_or_log_mismatch')
    with tempfile.TemporaryDirectory(prefix='ng8-compile-recheck-') as temporary:
        actual = compiler.inspect_compile_log(upstream, build_log, temporary, profile_version=3)
        if actual != profile:
            raise ValueError('actual_compile_log_reconstruction_mismatch')
        swift = inspect_swift_records(upstream, actual['swift_compiles'], source_report)
        bridge = []
        for line in log.decode('utf-8').splitlines():
            stripped = line.strip()
            if 'clang' not in stripped or not stripped.startswith(('/', "'", '"')):
                continue
            try:
                raw_arguments = shlex.split(stripped)
            except ValueError as error:
                raise ValueError('objc_compile_arguments') from error
            if not raw_arguments or Path(raw_arguments[0]).name != 'clang':
                continue
            arguments, used = compiler.expand_response_args(raw_arguments, upstream, temporary, clang_link_probe=True)
            if '-c' not in arguments or Path(_option(arguments, '-c')).name != 'NG8CaptureBridge.m':
                continue
            name = _relative(upstream, _option(arguments, '-c'))
            output = _relative(upstream, _option(arguments, '-o'))
            triple = _option(arguments, '-target')
            if (name != 'LoopCtrlUITests/NG8CaptureBridge.m' or not triple.startswith('arm64-apple-ios')
                    or '-simulator' in triple or '-macabi' in triple
                    or not output.startswith('build/') or '/Debug-iphoneos/' not in output
                    or '/LoopCtrlUITests.build/' not in output or not output.endswith('/NG8CaptureBridge.o')):
                raise ValueError('probe_objc_target_or_membership')
            digest = sha(_safe_file(upstream / name))
            if source_report['final_source_sha256'].get(name) != digest:
                raise ValueError('probe_objc_source_changed')
            bridge.append({'source': name, 'sha256': digest, 'object': output,
                'target_triple': triple, 'command_sha256': sha(stripped.encode()),
                'response_files': used})
        if len(bridge) != 1:
            raise ValueError('probe_objc_compile_evidence_missing_or_duplicate')
    return {'strict_native_profile': profile, 'probe_swift': swift, 'probe_objc': bridge,
            'build_log_sha256': sha(log)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('upstream', type=Path)
    parser.add_argument('driver', type=Path)
    parser.add_argument('ipa', type=Path)
    parser.add_argument('--build-log', type=Path, required=True)
    parser.add_argument('--compiler-profile', type=Path, required=True)
    parser.add_argument('--build-number', required=True)
    parser.add_argument('--source-zip', type=Path)
    args = parser.parse_args()
    sources = inspect_sources(args.upstream, args.driver)
    proof = inspect_compiler(args.upstream, args.build_log, args.compiler_profile, sources)
    try:
        report = inspect_probe_ipa(args.ipa, build_number=args.build_number,
            source_sha256=sources['overlay_manifest_sha256'], stamp=sources['build_stamp']['value'],
            products=args.upstream / 'build/Build/Products/Debug-iphoneos')
    except ValueError as error:
        diagnostic = getattr(error, '_ng8_identity_diagnostic', None)
        if diagnostic is not None:
            print(json.dumps(diagnostic, sort_keys=True), flush=True)
        raise
    # Recheck the complete input set at the package-writing boundary, including
    # the specifically materialized link, after compiler and ZIP inspection.
    _fixed_link(overlay._root(args.upstream))
    for name, digest in sources['complete_source_sha256'].items():
        actual_name = MATERIALIZED_LINKS.get(name, name)
        prefix, relative = actual_name.split('/', 1)
        overlay._name(relative)
        root = args.driver if prefix == 'driver' else args.upstream
        if prefix not in ('driver', 'upstream') or sha(_safe_file(root / relative)) != digest:
            raise ValueError('source_changed_before_package_report')
    sources.pop('manifest')
    report.update(sources)
    report.update({'schema': 'ng8-probe-build-manifest-v1', 'compiler_evidence': proof,
        'service_mode': 'iphone8-capture-only-v1', 'capability': 'necrogold_capture_probe_v1',
        'input_authorized': False, 'device_acceptance': 'not_run', 'callback_return_verified': False})
    report['toolchain'] = {name: subprocess.check_output(command, text=True, timeout=30).strip()
        for name, command in {'xcode': ['xcodebuild', '-version'], 'swift': ['swiftc', '--version'],
                             'rust': ['rustc', '--version'], 'xcodegen': ['xcodegen', '--version']}.items()}
    if args.source_zip:
        report['complete_source_zip'] = inspect_source_zip(args.source_zip, sources['complete_source_sha256'])
    else:
        report['complete_source_zip'] = {'verified': False, 'status': 'awaiting_generation'}
    destination = args.ipa.parent
    (destination / 'iphone8-probe-build-manifest.json').write_text(json.dumps(report, indent=2) + '\n')
    sums = report['ipa_sha256'] + '  ' + args.ipa.name + '\n'
    if args.source_zip:
        sums += report['complete_source_zip']['sha256'] + '  ' + args.source_zip.name + '\n'
    (destination / 'SHA256SUMS.txt').write_text(sums)
    print(json.dumps({'status': 'verified', 'build': report['build'], 'ipa_sha256': report['ipa_sha256'],
        'source_files': len(report['complete_source_sha256']), 'source_zip_verified': report['complete_source_zip']['verified'],
        'input_authorized': False, 'device_acceptance': 'not_run'}, sort_keys=True))


if __name__ == '__main__':
    main()
